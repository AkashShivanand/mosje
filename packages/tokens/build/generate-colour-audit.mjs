import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

import { hexToOklch, deltaE, hueDelta } from "./oklch.mjs";
import { contrastRatio } from "./ramp.mjs";
import { ANCHORS } from "./brand-ramps.mjs";

const here = (p) => new URL(p, import.meta.url).pathname;
const css = readFileSync(here("../dist/tokens.css"), "utf8");

function block(selector) {
  const i = selector ? css.indexOf(selector) : css.indexOf(":root {");
  if (i < 0) return null;
  const open = css.indexOf("{", i);
  return new Map(
    [...css.slice(open, css.indexOf("\n}", open)).matchAll(/^\s*(--[A-Za-z0-9-]+)\s*:\s*([^;]+);/gm)]
      .map((m) => [m[1], m[2].trim()]),
  );
}
const ROOT = block(null);
const resolverFor = (b) => {
  const map = b ? new Map([...ROOT, ...b]) : ROOT;
  return function resolve(name, depth = 0) {
    if (depth > 8) return null;
    const v = map.get(name) ?? ROOT.get(name);
    if (!v) return null;
    const ref = v.match(/^var\((--[A-Za-z0-9-]+)\)$/);
    return ref ? resolve(ref[1], depth + 1) : v;
  };
};

const MODES_KEYS = ["blue", "navy"];
const MODES = {
  blue: resolverFor(null),
  navy: resolverFor(block('[data-brand="navy"]')),
};

/** The six DBIM conformance previews, measured separately — they are not estate brands. */
const DBIM_MODES = Object.fromEntries(
  [...css.matchAll(/^\[data-brand="(dbim-[a-z-]+)"\]/gm)]
    .map((m) => m[1])
    .filter((id, i, a) => a.indexOf(id) === i)
    .map((id) => [id, resolverFor(block(`[data-brand="${id}"]`))]),
);
const HEX = /^#[0-9a-f]{6}$/i;
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const NEUTRAL_STEPS = [0, ...STEPS, 1000];

/** Every ramp, and what kind of thing it is. */
const RAMPS = [
  ["primaryScale", "brand", "The only ramp a brand swap repaints."],
  ["secondaryScale", "brand", "India Saffron #FF671F from the SAMAVESH logo. Brand-invariant."],
  ["accentScale", "brand", "India Green #046A38 from the SAMAVESH logo. Brand-invariant, and the same green as success."],
  ["successScale", "functional", "Deliberately identical to accentScale."],
  ["dangerScale", "functional", "Anchor #ec5042 at rung 400 — the rung its L\\* 64 says, which is what took `bolder` from 4.40:1 to AA."],
  ["warningScale", "functional", "Anchor at rung 300, rotated to hue 76: the ramp used to carry two hues, and 66 collided with saffron."],
  ["infoScale", "functional", "Anchor #1a73e8 at rung 500. Sits ~3 degrees from primary; see the separation table."],
  ["neutralScale", "neutral", "13 steps: 0 is pure white and 1000 pure black, which are achromatic and belong here only. Hue locked to the brand's primary."],
];

function rampRows(mode, family) {
  const res = MODES[mode];
  const steps = family === "neutralScale" ? NEUTRAL_STEPS : STEPS;
  const out = [];
  let prev = null;
  for (const s of steps) {
    const hex = res(`--sa-color-${family}-${s}`);
    if (!HEX.test(hex ?? "")) continue;
    const o = hexToOklch(hex);
    out.push({ step: s, hex, L: o.L, C: o.C, H: o.H, dL: prev === null ? null : prev - o.L, onWhite: contrastRatio(hex, "#ffffff") });
    prev = o.L;
  }
  return out;
}

function shape(rows) {
  const dl = rows.slice(1).map((r) => r.dL);
  const chromatic = rows.filter((r) => r.C > 0.01).map((r) => r.H);
  return {
    steps: rows.length,
    min: Math.min(...dl),
    max: Math.max(...dl),
    monotonic: dl.every((d) => d > 0),
    hueDrift: chromatic.length > 1 ? Math.max(...chromatic) - Math.min(...chromatic) : 0,
  };
}

