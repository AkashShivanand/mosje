/**
 * Generate `docs/design-system/colour-system.md` — the colour system's reference document.
 *
 * GENERATED, for the same reason everything else here is: a colour document with hand-typed
 * hexes is a second source of truth, and the 2026-08-11 audit found three of those in this
 * repo already lying (the TS mirror, the alpha tiers, the docs pages). Every number below is
 * read from `dist/tokens.css` at build time, so the document cannot describe a system that
 * does not exist.
 *
 * Run: node build/generate-colour-audit.mjs   (or as part of `npm run build -w @mosje/tokens`)
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

import { hexToOklch, deltaE, hueDelta } from "./oklch.mjs";
import { contrastRatio } from "./ramp.mjs";
import { ANCHORS } from "./brand-ramps.mjs";

const here = (p) => new URL(p, import.meta.url).pathname;
const css = readFileSync(here("../dist/tokens.css"), "utf8");

function block(selector) {
  const i = selector ? css.indexOf(selector) : css.indexOf(":root {");
  if (i < 0) return null;
  const open = css.indexOf("{", i);
  return new Map(
    [...css.slice(open, css.indexOf("\n}", open)).matchAll(/^\s*(--[A-Za-z0-9-]+)\s*:\s*([^;]+);/gm)]
      .map((m) => [m[1], m[2].trim()]),
  );
}
const ROOT = block(null);
const resolverFor = (b) => {
  const map = b ? new Map([...ROOT, ...b]) : ROOT;
  return function resolve(name, depth = 0) {
    if (depth > 8) return null;
    const v = map.get(name) ?? ROOT.get(name);
    if (!v) return null;
    const ref = v.match(/^var\((--[A-Za-z0-9-]+)\)$/);
    return ref ? resolve(ref[1], depth + 1) : v;
  };
};

const MODES = {
  blue: resolverFor(null),
  navy: resolverFor(block('[data-brand="navy"]')),
  dbim: resolverFor(block('[data-brand="dbim"]')),
};
const HEX = /^#[0-9a-f]{6}$/i;
const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const NEUTRAL_STEPS = [0, ...STEPS, 1000];

/** Every ramp, and what kind of thing it is. */
const RAMPS = [
  ["primaryScale", "brand", "The only ramp a brand swap repaints."],
  ["secondaryScale", "brand", "India Saffron #FF671F from the SAMAVESH logo. Brand-invariant."],
  ["accentScale", "brand", "India Green #046A38 from the SAMAVESH logo. Brand-invariant, and the same green as success."],
  ["successScale", "functional", "Deliberately identical to accentScale."],
  ["dangerScale", "functional", "Anchor #ec5042 at rung 400 — the rung its L\\* 64 says, which is what took `bolder` from 4.40:1 to AA."],
  ["warningScale", "functional", "Anchor at rung 300, rotated to hue 76: the ramp used to carry two hues, and 66 collided with saffron."],
  ["infoScale", "functional", "Anchor #1a73e8 at rung 500. Sits ~3 degrees from primary; see the separation table."],
  ["neutralScale", "neutral", "13 steps: 0 is pure white and 1000 pure black, which are achromatic and belong here only. Hue locked to the brand's primary."],
];

function rampRows(mode, family) {
  const res = MODES[mode];
  const steps = family === "neutralScale" ? NEUTRAL_STEPS : STEPS;
  const out = [];
  let prev = null;
  for (const s of steps) {
    const hex = res(`--sa-color-${family}-${s}`);
    if (!HEX.test(hex ?? "")) continue;
    const o = hexToOklch(hex);
    out.push({ step: s, hex, L: o.L, C: o.C, H: o.H, dL: prev === null ? null : prev - o.L, onWhite: contrastRatio(hex, "#ffffff") });
    prev = o.L;
  }
  return out;
}

function shape(rows) {
  const dl = rows.slice(1).map((r) => r.dL);
  const chromatic = rows.filter((r) => r.C > 0.01).map((r) => r.H);
  return {
    steps: rows.length,
    min: Math.min(...dl),
    max: Math.max(...dl),
    monotonic: dl.every((d) => d > 0),
    hueDrift: chromatic.length > 1 ? Math.max(...chromatic) - Math.min(...chromatic) : 0,
  };
}

/* ------------------------------------------------------------------ the document */

const lines = [];
const p = (s = "") => lines.push(s);

p("<!-- GENERATED by packages/tokens/build/generate-colour-audit.mjs — do not edit.");
p("     Every number is read from dist/tokens.css at build time, so this document cannot");
p("     describe a system that does not exist. Regenerate with:");
p("       node packages/tokens/build/generate-colour-audit.mjs -->");
p();
p("# The SAMAVESH colour system");
p();
p("Three brand modes on `data-brand`. A brand swap repaints the **primary** ramp and the");
p("**neutral** greys, and nothing else — secondary and accent are SAMAVESH logo colours and are");
p("therefore constants of the identity, not variants of it.");
p();
p("| mode | key colour | in Figma? |");
p("|------|-----------|-----------|");
p("| `blue` (default) | `#0373DF` gov-blue | yes |");
p("| `navy` | `#003366` | yes |");
p("| `dbim` | `#162F6A` — DBIM's own key colour | **no, code-only by standing instruction** |");
p();
p("`dbim` transcribes DBIM's published Blue primary palette rather than deriving a ramp from one");
p("anchor. DBIM issues five numbered shades (1 = darkest = key colour, 5 = lightest) and all five");
p("are reproduced verbatim; the intervening rungs are interpolated. Source: `docs/source-brd/MoSJE");
p("DBIM Audit.pdf` p.14, reproducing DBIM section 2.1 Figure 1.");
p();
const dbimShades = ANCHORS["primaryRamp.dbim"]?.dbimShades ?? {};
p("| DBIM shade | rung | value | rule |");
p("|---|---|---|---|");
for (const [rung, shade] of Object.entries(dbimShades).sort((a, b) => a[1] - b[1])) {
  const hex = MODES.dbim(`--sa-color-primaryScale-${rung}`);
  const rule = shade === 1 ? "key colour — icons and footer (DBIM 3.7, 5.6)" : shade === 2 ? "text may use shade 1 or 2 (DBIM 4.4)" : "";
  p(`| ${shade} | ${rung} | \`${hex}\` | ${rule} |`);
}
p();

p("## Ramp inventory");
p();
p("Eleven steps on every chromatic ramp (50–950, matching UX4G 3.0); thirteen on neutral.");
p();
p("| ramp | kind | steps | ΔL\\* range | monotonic | hue drift | note |");
p("|---|---|---|---|---|---|---|");
for (const [family, kind, note] of RAMPS) {
  const rows = rampRows("blue", family);
  const s = shape(rows);
  const warn = s.min < 4 || s.max > 16 || s.hueDrift > 6;
  p(
    `| \`${family}\` | ${kind} | ${s.steps} | ${s.min.toFixed(1)}–${s.max.toFixed(1)}${warn ? " ⚠️" : ""} | ` +
      `${s.monotonic ? "yes" : "**NO**"} | ${s.hueDrift.toFixed(0)}° | ${note} |`,
  );
}
p();
const flagged = RAMPS.filter(([f]) => {
  const s = shape(rampRows("blue", f));
  return s.min < 4 || s.max > 16 || s.hueDrift > 6;
}).map(([f]) => f);
p(
  flagged.length === 0
    ? "**Every ramp satisfies the shape rule** — each step 4–16 L\\* from the last, monotonic, hue " +
      "held within ~6°, chroma on a single arc. There is nothing to flag. All eight are generated " +
      "from the anchors in `build/brand-ramps.mjs`; the last four (danger, warning, info, neutral) " +
      "were rebuilt on 2026-08-11."
    : `⚠️ marks a ramp outside the shape rule the generator enforces: ${flagged.join(", ")}. ` +
      "Fix it in `build/brand-ramps.mjs` and re-run — the shape is a property of the anchors, not " +
      "something to be edited step by step.",
);
p();

p("## Accessibility");
p();
p("Measured against each token's own declared partner, in every mode. `on/*` pairs a fill with");
p("the ink chosen for it BY MEASUREMENT in the worst brand, not by assumption.");
p();
p("| mode | on/* pairings | below AA (4.5:1) |");
p("|---|---|---|");
const onNames = [...ROOT.keys()].filter((n) => n.startsWith("--sa-on-bg-"));
const failures = {};
for (const [mode, res] of Object.entries(MODES)) {
  let checked = 0;
  const bad = [];
  for (const on of onNames) {
    const fg = res(on);
    const bg = res(on.replace("--sa-on-bg-", "--sa-bg-"));
    if (!HEX.test(fg ?? "") || !HEX.test(bg ?? "")) continue;
    checked++;
    const r = contrastRatio(fg, bg);
    if (r + 0.005 < 4.5) bad.push(`\`${on.replace("--sa-on-bg-", "")}\` ${r.toFixed(2)}`);
  }
  failures[mode] = bad;
  p(`| ${mode} | ${checked} | ${bad.length ? bad.join(", ") : "none"} |`);
}
p();
const worst = Math.max(...Object.values(failures).map((b) => b.length));
p(
  worst === 0
    ? "**No shortfalls, in any mode.** Every `on/*` foreground is AA-readable on the fill it names. " +
      "The last two — `status-error-bolder` at 4.40:1 and `status-warning-bolder` at 4.46:1 — closed " +
      "on 2026-08-11 when the danger and warning ramps were re-anchored at the rung their lightness " +
      "says (400 and 300, not 500), taking those rungs to 6.68:1 and 5.68:1."
    : "Each shortfall above is a FILL that no ink can rescue — the remedy is the ramp, not the " +
      "foreground. `test/on-pair-contrast.mjs` pins them in a list that may only shrink.",
);
p();

p("## Hue separation");
p();
p("Two families that mean different things must look different. Measured at matched rungs, worst");
p("case across all three modes, in OKLab. A pair passes on hue **or** perceptual distance —");
p("hue alone is too weak (blue and navy are 9° apart and separated by lightness) and too strong");
p("(red and orange are adjacent and can never separate in hue).");
p();
p("| pair | worst Δhue | worst ΔE | verdict |");
p("|---|---|---|---|");
const FAMILY_BG = {
  primary: "bg-brand-primary", secondary: "bg-brand-secondary", accent: "bg-brand-accent",
  success: "bg-status-success", error: "bg-status-error", warning: "bg-status-warning", info: "bg-status-info",
};
const RUNGS = ["subtler", "subtle", "bold", "bolder", "boldest"];
const names = Object.keys(FAMILY_BG);
const pairs = [];
for (let i = 0; i < names.length; i++) {
  for (let j = i + 1; j < names.length; j++) {
    let worst = null;
    for (const [, res] of Object.entries(MODES)) {
      for (const rung of RUNGS) {
        const a = res(`--sa-${FAMILY_BG[names[i]]}-${rung}`);
        const b = res(`--sa-${FAMILY_BG[names[j]]}-${rung}`);
        if (!HEX.test(a ?? "") || !HEX.test(b ?? "")) continue;
        const dE = deltaE(a, b);
        const dH = Math.abs(hueDelta(hexToOklch(a).H, hexToOklch(b).H));
        if (!worst || dE < worst.dE) worst = { dE, dH };
      }
    }
    if (worst) pairs.push({ pair: `${names[i]} · ${names[j]}`, ...worst });
  }
}
for (const x of pairs.sort((a, b) => a.dE - b.dE).slice(0, 8)) {
  const ok = x.dH >= 30 || x.dE >= 12;
  const verdict = x.dE < 1 ? "**deliberately one colour**" : ok ? "separated" : "**too close**";
  p(`| ${x.pair} | ${x.dH.toFixed(0)}° | ${x.dE.toFixed(1)} | ${verdict} |`);
}
p();
p("Only the closest eight are listed; every other pair clears comfortably. `accent · success` is");
p("one colour on purpose, and `info · primary` is a pre-existing union recorded in the gate.");
p();
p("---");
p();
p("Enforced by `packages/tokens/test/` — hue separation, on-pair contrast, the prominence");
p("contract, brand-swap parity and the ramp shape rule all run on every build.");
p();

mkdirSync(here("../../../docs/design-system"), { recursive: true });
writeFileSync(here("../../../docs/design-system/colour-system.md"), lines.join("\n"));
process.stdout.write(`✓ generated docs/design-system/colour-system.md (${lines.length} lines)\n`);
