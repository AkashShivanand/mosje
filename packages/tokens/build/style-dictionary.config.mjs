/**
 * Wrap a CSS format so every `var(--sa-…)` it emits carries the referent's tier marker
 * (spec §4.1). The alias tables inside these formats predate tier markers; this makes the
 * whole surface consistent without hand-editing every hardcoded target.
 */
const tierAware = (fmt) => ({
  ...fmt,
  format: (args) =>
    retierCss(
      fmt.format(args),
      makeRetier(args.dictionary.allTokens, { tierOfFile, toCssName }),
    ),
});

const val = (t) => (t.$value !== undefined ? t.$value : t.value);

// Build a nested plain object of resolved values from the flat token list.
function nest(tokens) {
  const obj = {};
  for (const t of tokens) {
    let node = obj;
    for (const p of t.path.slice(0, -1)) node = node[p] ??= {};
    node[t.path.at(-1)] = val(t);
  }
  return obj;
}

StyleDictionary.registerFormat(figmaVariables);
StyleDictionary.registerFormat(tierAware(legacyDsCss));
StyleDictionary.registerFormat(tierAware(ux4gParityCss));

/**
 * The six DBIM conformance brands, expanded from a rule instead of stored as ~900 JSON
 * entries. See `build/dbim-brand-modes.mjs` for what they are and why they are synthesised.
 * Runs before the formats, so `legacy-ds-css` sees the extra `colorModes` keys and emits one
 * `[data-brand="dbim-…"]` block per group with its alias closure, exactly as for any brand.
 */
StyleDictionary.registerPreprocessor({
  name: "mosje/dbim-brands",
  preprocessor: (dictionary) => {
    addDbimBrandModes(dictionary);
    return dictionary;
  },
});

StyleDictionary.registerFormat({
  name: "ts/nested",
  format: ({ dictionary }) =>
    `// GENERATED by @mosje/tokens — do not edit.\n` +
    `export const tokens = ${JSON.stringify(nest(dictionary.allTokens), null, 2)} as const;\n` +
    `export default tokens;\n`,
});

StyleDictionary.registerFormat({
  name: "json/nested-values",
  format: ({ dictionary }) => JSON.stringify(nest(dictionary.allTokens), null, 2) + "\n",
});

