// Tailwind v4 @theme: expose semantic colors as --color-* mapped to the --sa-* vars.
StyleDictionary.registerFormat({
  name: "css/tailwind-v4",
  format: ({ dictionary }) => {
    // The target name MUST come from toCssName/tierOfFile, not from a hand-rolled
    // `--sa-${path}`. Hand-rolling it dropped the tier marker, so every Tier-1 entry
    // pointed at `--sa-color-*` while the sheet actually declares `--sa-ref-color-*`:
    // 111 of these aliased a custom property that does not exist, and every Tailwind v4
    // colour utility built on them silently resolved to nothing.
    const vars = dictionary.allTokens
      .filter((t) => t.path[0] === "color")
      .map((t) => `  --color-${t.path.slice(1).join("-")}: var(${toCssName(t.path, tierOfFile(t.filePath))});`);
    return `/* GENERATED by @mosje/tokens. */\n@theme inline {\n${vars.join("\n")}\n}\n`;
  },
});

// NB: no fontFamily/css — font-family tokens are authored in final CSS form (double-quoted)
