import StyleDictionary from "style-dictionary";
import { legacyDsCss } from "./formats/legacy-ds-css.mjs";

const val = (t) => (t.$value !== undefined ? t.$value : t.value);

// Build a nested plain object of resolved values from the flat token list.
function nest(tokens) {
  const obj = {};
  for (const t of tokens) {
    let node = obj;
    for (const p of t.path.slice(0, -1)) node = node[p] ??= {};
    node[t.path.at(-1)] = val(t);
  }
  return obj;
}

StyleDictionary.registerFormat(legacyDsCss);

StyleDictionary.registerFormat({
  name: "ts/nested",
  format: ({ dictionary }) =>
    `// GENERATED by @mosje/tokens — do not edit.\n` +
    `export const tokens = ${JSON.stringify(nest(dictionary.allTokens), null, 2)} as const;\n` +
    `export default tokens;\n`,
});

StyleDictionary.registerFormat({
  name: "json/nested-values",
  format: ({ dictionary }) => JSON.stringify(nest(dictionary.allTokens), null, 2) + "\n",
});

// Tailwind v3 preset: curated utility names → legacy CSS vars (stable for portals).
StyleDictionary.registerFormat({
  name: "tailwind/v3",
  format: () => {
    const colors = {
      "gov-blue": "var(--ds-primary)",
      primary: "var(--ds-primary)",
      "primary-tonal": "var(--ds-primary-tonal)",
      success: "var(--ds-success)",
      danger: "var(--ds-danger)",
      warning: "var(--ds-warning)",
      saffron: "var(--ds-saffron)",
      ink: "var(--ds-ink)",
      surface: "var(--ds-surface)",
    };
    const borderRadius = {
      xs: "var(--ds-radius-xs)",
      sm: "var(--ds-radius-sm)",
      md: "var(--ds-radius-md)",
      pill: "var(--ds-radius-pill)",
    };
    return (
      `// GENERATED by @mosje/tokens.\n` +
      `module.exports = { theme: { extend: { colors: ${JSON.stringify(colors, null, 2)}, ` +
      `borderRadius: ${JSON.stringify(borderRadius, null, 2)} } } };\n`
    );
  },
});

// Tailwind v4 @theme: expose semantic colors as --color-* mapped to the --sa-* vars.
StyleDictionary.registerFormat({
  name: "css/tailwind-v4",
  format: ({ dictionary }) => {
    const vars = dictionary.allTokens
      .filter((t) => t.path[0] === "color")
      .map((t) => `  --color-${t.path.slice(1).join("-")}: var(--sa-${t.path.join("-")});`);
    return `/* GENERATED by @mosje/tokens. */\n@theme inline {\n${vars.join("\n")}\n}\n`;
  },
});

// NB: no fontFamily/css — font-family tokens are authored in final CSS form (double-quoted)
// and must pass through verbatim to match the legacy contract. No size/rem — px is preserved.
const TRANSFORMS = ["attribute/cti", "name/kebab", "color/css"];

const sd = new StyleDictionary({
  source: ["src/primitive.json", "src/semantic.json", "src/component.json"],
  platforms: {
    css: {
      transforms: TRANSFORMS,
      buildPath: "dist/",
      files: [
        { destination: "tokens.css", format: "css/legacy-ds" },
        { destination: "tokens-tailwind.css", format: "css/tailwind-v4" },
      ],
    },
    ts: {
      transforms: TRANSFORMS,
      buildPath: "dist/",
      files: [{ destination: "tokens.ts", format: "ts/nested" }],
    },
    tw3: {
      transforms: TRANSFORMS,
      buildPath: "dist/",
      files: [{ destination: "tailwind-v3.cjs", format: "tailwind/v3" }],
    },
    figma: {
      transforms: TRANSFORMS,
      buildPath: "dist/",
      files: [{ destination: "figma.tokens.json", format: "json/nested-values" }],
    },
    // Emit the generated CSS straight into @mosje/design-system so its existing consumers
    // (e.g. dosje's `@import "@mosje/design-system/tokens.css"`) get real CSS with no extra
    // package resolution. This file is GENERATED — do not hand-edit it.
    designSystemCss: {
      transforms: TRANSFORMS,
      buildPath: "../design-system/",
      files: [{ destination: "tokens.css", format: "css/legacy-ds" }],
    },
  },
});

await sd.hasInitialized;
await sd.buildAllPlatforms();
console.log("✓ @mosje/tokens built");
