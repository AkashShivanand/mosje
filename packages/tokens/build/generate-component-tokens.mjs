/**
 * Expand src/component-matrix.json into DTCG Tier-3 tokens.
 *
 * Spec §7.3: "Produced by build/generate-component-tokens.mjs from a matrix JSON. A human
 * never types these names; drift is impossible by construction."
 *
 * Every generated path is validated against the grammar before it is written, so the
 * generator cannot mint a name the system would reject. Run:
 *
 *     node build/generate-component-tokens.mjs            # write src/component.generated.json
 *     node build/generate-component-tokens.mjs --check    # fail if the file is stale
 */

import { readFileSync, writeFileSync } from "node:fs";
import { parse, toCssName } from "./grammar.mjs";

const here = (p) => new URL(p, import.meta.url).pathname;
const matrix = JSON.parse(readFileSync(here("../src/component-matrix.json"), "utf8"));

/** Resolve a matrix cell to a DTCG value or reference. */
function resolveCell(spec, intent, isInverse) {
  const { scale, onFill } = matrix.intents[intent];

  if (spec === "onFill") return onFill;
  // Literal, not a reference: there is no transparent entry on neutralScale, and adding one
  // would put a non-colour in a colour ramp. rgba(0,0,0,0) survives the color/css transform
  // where the `transparent` keyword does not.
  if (spec === "transparent") return "rgba(0, 0, 0, 0)";
  if (spec === "white") return "{color.neutralScale.0}";
  if (spec === "neutralDisabled") return "{color.text.disabled}";
  if (/^neutral(\d+)$/.test(spec)) return `{color.neutralScale.${spec.slice(7)}}`;

  // White at a named alpha — used only by the inverse qualifier, so a button on a solid
  // surface works on ANY brand colour rather than assuming one.
  const alpha = /^white(\d+)$/.exec(spec);
  if (alpha) return `rgba(255, 255, 255, ${(Number(alpha[1]) / 100).toFixed(2)})`;

  if (/^\d+$/.test(spec)) return `{color.${scale}.${spec}}`;

  throw new Error(`unrecognised matrix cell ${JSON.stringify(spec)} (intent ${intent}, inverse=${isInverse})`);
}

function setPath(root, path, node) {
  let cur = root;
  for (const seg of path.slice(0, -1)) cur = cur[seg] ??= {};
  cur[path.at(-1)] = node;
}

// NOT nested under `cmp`. The tier is derived from the source FILE (grammar.tierOfFile),
// so the DTCG path here is identical to the Figma variable path and the `cmp` marker is
// added only at CSS projection. Nesting would put a synthetic segment mid-path and break
// that correspondence — spec §4.1.
const out = { $description: "GENERATED by build/generate-component-tokens.mjs — do not edit.", action: {} };
const generated = [];
const errors = [];

for (const intent of Object.keys(matrix.intents)) {
  // Base variants.
  for (const [variant, states] of Object.entries(matrix.variants)) {
    for (const [state, cells] of Object.entries(states)) {
      if (state.startsWith("$")) continue;
      // Per-intent overrides — the ramps are not perceptually equivalent at equal steps.
      const patch = matrix.overrides?.[intent]?.[variant]?.[state] ?? {};
      for (const [property, baseSpec] of Object.entries({ ...cells, ...patch })) {
        const spec = baseSpec;
        const path = ["action", intent, variant, state, property];
        const check = parse(path, "cmp");
        if (!check.ok) {
          errors.push(`${path.join("/")} — ${check.error}`);
          continue;
        }
        setPath(out, path, {
          $type: "color",
          $value: resolveCell(spec, intent, false),
          $description: `${intent} ${variant} button, ${state} state, ${property}`,
        });
        generated.push(toCssName(path, "cmp"));
      }
    }
  }

  // Inverse qualifier — only meaningful for primary/secondary.
  for (const [variant, states] of Object.entries(matrix.inverse)) {
    for (const [state, cells] of Object.entries(states)) {
      for (const [property, spec] of Object.entries(cells)) {
        const path = ["action", intent, variant, "inverse", state, property];
        const check = parse(path, "cmp");
        if (!check.ok) {
          errors.push(`${path.join("/")} — ${check.error}`);
          continue;
        }
        setPath(out, path, {
          $type: "color",
          $value: resolveCell(spec, intent, true),
          $description: `${intent} ${variant} button on a solid brand surface, ${state} state, ${property}`,
        });
        generated.push(toCssName(path, "cmp"));
      }
    }
  }
}

if (errors.length) {
  console.error(`✗ ${errors.length} generated path(s) fail the grammar:`);
  for (const e of errors.slice(0, 20)) console.error("   " + e);
  process.exit(1);
}

const json = JSON.stringify(out, null, 2) + "\n";
const target = here("../src/component.generated.json");

if (process.argv.includes("--check")) {
  let existing = null;
  try {
    existing = readFileSync(target, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (existing !== json) {
    console.error("✗ src/component.generated.json is stale — run `node build/generate-component-tokens.mjs`");
    process.exit(1);
  }
  console.log(`✓ component.generated.json is current (${generated.length} tokens)`);
} else {
  writeFileSync(target, json);
  console.log(`✓ generated ${generated.length} Tier-3 tokens → src/component.generated.json`);
  console.log(`  e.g. ${generated[0]}`);
  console.log(`       ${generated.at(-1)}`);
}

export { generated };
