/* ============================================================================
   Bakes a quantised India TopoJSON into static SVG path data so the DS IndiaMap
   needs no d3-geo / topojson-client at runtime.

   Usage:
     node generate-india-paths.mjs [path/to/india-states.topo.json]

   Projection matches the legacy SMILE map 1:1:
     geoMercator().center([82.5, 22]).scale(950).translate([400, 280])
     viewBox "0 0 800 560"
   ============================================================================ */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const INPUT =
  process.argv[2] ??
  resolve(__dirname, "../../../../../../apps/portals/smile-admin/public/india-states.topo.json");
const OUTPUT = resolve(__dirname, "india-states.paths.ts");

const VIEW_W = 800;
const VIEW_H = 560;
const CENTER = [82.5, 22];
const SCALE = 950;
const TRANSLATE = [400, 280];

const DEG = Math.PI / 180;
const mercator = (lonDeg, latDeg) => [
  lonDeg * DEG,
  Math.log(Math.tan(Math.PI / 4 + (latDeg * DEG) / 2)),
];
const [cx, cy] = mercator(CENTER[0], CENTER[1]);

/** lon/lat → screen pixel, matching d3 geoMercator with the params above. */
function project(lon, lat) {
  const [mx, my] = mercator(lon, lat);
  return [TRANSLATE[0] + SCALE * (mx - cx), TRANSLATE[1] - SCALE * (my - cy)];
}

const topo = JSON.parse(readFileSync(INPUT, "utf8"));
const { scale: tScale, translate: tTranslate } = topo.transform;

// Decode each delta-encoded, quantised arc into absolute lon/lat coordinates.
const decodedArcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * tScale[0] + tTranslate[0], y * tScale[1] + tTranslate[1]];
  });
});

function arcPoints(index) {
  if (index >= 0) return decodedArcs[index];
  return decodedArcs[~index].slice().reverse();
}

function ringToPath(arcIndexes) {
  const pts = [];
  for (const ai of arcIndexes) {
    const seg = arcPoints(ai);
    for (let i = 0; i < seg.length; i++) {
      // Skip the duplicated join point between consecutive arcs.
      if (pts.length && i === 0) continue;
      pts.push(seg[i]);
    }
  }
  const proj = pts.map(([lon, lat]) => project(lon, lat));
  return (
    proj
      .map(([px, py], i) => `${i === 0 ? "M" : "L"}${px.toFixed(1)} ${py.toFixed(1)}`)
      .join(" ") + " Z"
  );
}

function geometryToPath(geom) {
  if (geom.type === "Polygon") {
    return geom.arcs.map(ringToPath).join(" ");
  }
  if (geom.type === "MultiPolygon") {
    return geom.arcs.map((poly) => poly.map(ringToPath).join(" ")).join(" ");
  }
  return "";
}

const states = topo.objects.states.geometries
  .map((g) => ({
    id: String(g.properties.st_code ?? g.properties.st_nm),
    name: String(g.properties.st_nm),
    d: geometryToPath(g),
  }))
  .filter((s) => s.d)
  .sort((a, b) => a.name.localeCompare(b.name));

const body =
  `/* GENERATED by generate-india-paths.mjs — do not edit.\n` +
  `   Regenerate: node packages/design-system/components/data-display/charts/geo/generate-india-paths.mjs */\n\n` +
  `export const INDIA_STATES_VIEWBOX = "0 0 ${VIEW_W} ${VIEW_H}";\n\n` +
  `export interface IndiaRegionPath {\n  /** State code (st_code). */\n  id: string;\n  /** State name (st_nm). */\n  name: string;\n  /** SVG path data in the INDIA_STATES_VIEWBOX coordinate system. */\n  d: string;\n}\n\n` +
  `export const INDIA_STATES_PATHS: IndiaRegionPath[] = ${JSON.stringify(states, null, 0)
    .replace(/\},\{/g, "},\n  {")
    .replace(/^\[/, "[\n  ")
    .replace(/\]$/, ",\n]")};\n`;

writeFileSync(OUTPUT, body);
console.log(`✓ wrote ${states.length} states → ${OUTPUT}`);
