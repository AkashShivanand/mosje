#!/usr/bin/env node
/**
 * Mirror the PM-AJAY map-points feed into a committed, state-level snapshot.
 *
 * WHY A SNAPSHOT EXISTS AT ALL. `.claude/rules/live-data-fallback.md`: a figure
 * the department publishes is never replaced on this estate by a dash, a zero or
 * "not yet reported". The reach map therefore needs something to draw when the
 * feed is unreachable, and that something has to be the department's own last
 * published figures rather than an invention.
 *
 * WHY IT IS AGGREGATED HERE AND NOT IN THE APP. The live payload is ~3.5 MB —
 * 19,768 village points and 203 hostel points, each with coordinates. The map
 * draws states, so all the page ever needs is two lists of about two dozen rows.
 * Aggregating at the edge keeps the snapshot in the repository readable and
 * keeps the server render from shipping a megabyte of coordinates it discards.
 *
 * WHY IT IS NOT REGENERATED BY THE BUILD. A snapshot is a point in time; a
 * snapshot that silently follows the feed is not a fallback, it is a second copy
 * of the feed with a stale date on it. Run this deliberately, read the diff, and
 * move `AS_ON` in the same commit:
 *
 *     node scripts/build-pmajay-map-snapshot.mjs
 *
 * `--check` re-fetches and reports drift without writing, for the same reason
 * `tools/feed-drift` exists: knowing the mirror has moved is useful; failing a
 * build because a ministry API changed a number is not.
 */

import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/hub/src/lib/website/pmajay-map-snapshot.ts");

const BASE =
  process.env.NEXT_PUBLIC_PMAJAY_API ??
  "https://pmajay-api-admin.mosje.in/api/v1/admin/public/reports";

/**
 * "JAMMU AND KASHMIR" → "Jammu and Kashmir".
 *
 * The feed shouts every state name. `IndiaMap` matches case-insensitively so the
 * map would work either way, but the ranked list beside it is read by a person,
 * and a column of block capitals reads as an error message. Joining words stay
 * lowercase — "Andaman and Nicobar", not "Andaman And Nicobar".
 */
const JOINERS = new Set(["and", "of", "the"]);
function titleCase(raw) {
  return raw
    .toLowerCase()
    .split(/\s+/)
    .map((w, i) => (i > 0 && JOINERS.has(w) ? w : w.charAt(0).toUpperCase() + w.slice(1)))
    .join(" ");
}

function aggregate(points, stateKey, districtKey) {
  const byState = new Map();
  const districts = new Set();
  for (const p of points) {
    const state = titleCase(String(p[stateKey] ?? "").trim());
    if (!state) continue;
    byState.set(state, (byState.get(state) ?? 0) + 1);
    districts.add(`${p[stateKey]}:${p[districtKey]}`);
  }
  const rows = [...byState]
    .map(([state, value]) => ({ state, value }))
    // Descending by count, then alphabetical — `component-authoring.md` §10:
    // an enumeration is ordered logically, and a tie broken by chance is not.
    .sort((a, b) => b.value - a.value || a.state.localeCompare(b.state));
  return {
    rows,
    total: points.length,
    states: rows.length,
    districts: districts.size,
  };
}

async function fetchReach() {
  const res = await fetch(`${BASE}/map-points`, {
    signal: AbortSignal.timeout(60_000),
  });
  if (!res.ok) throw new Error(`map-points responded ${res.status}`);
  const body = await res.json();
  const data = body?.data;
  if (!data || !Array.isArray(data.vdp_villages) || !Array.isArray(data.hostels)) {
    throw new Error("map-points payload is missing vdp_villages or hostels");
  }
  return {
    villages: aggregate(data.vdp_villages, "state_name", "district_code"),
    hostels: aggregate(data.hostels, "state_name", "district_id"),
  };
}

function serialiseDataset(name, d) {
  const rows = d.rows.map((r) => `    { state: ${JSON.stringify(r.state)}, value: ${r.value} },`);
  return [
    `  ${name}: {`,
    `    total: ${d.total},`,
    `    states: ${d.states},`,
    `    districts: ${d.districts},`,
    `    rows: [`,
    ...rows.map((r) => `  ${r}`),
    `    ],`,
    `  },`,
  ].join("\n");
}

function render(reach, asOn) {
  return `/**
 * PM-AJAY reach, mirrored from the department's \`map-points\` feed.
 *
 * GENERATED — do not hand-edit. Refresh with:
 *
 *     node scripts/build-pmajay-map-snapshot.mjs
 *
 * and move \`PMAJAY_REACH_AS_ON\` in the same commit. It is deliberately NOT
 * rebuilt by \`npm run build\`: a mirror that silently tracks the feed is not a
 * fallback, it is a second copy of the feed wearing a stale date.
 *
 * ONE DATE PER DATASET, and that is not fussiness. GIA and hostels shared a
 * single \`AS_ON\` while being captured days apart, and the banner told readers
 * both were mirrored on a day only one of them was. Villages and hostels come
 * out of the same request here, so they genuinely share a date — but the field
 * stays per-run rather than per-file so the next dataset added cannot inherit
 * someone else's capture date by default.
 */

export interface ReachRow {
  /** State name, title-cased. \`IndiaMap\` matches it case- and "&"-insensitively. */
  state: string;
  value: number;
}

export interface ReachDataset {
  rows: ReachRow[];
  /** Points in the feed, before aggregation. */
  total: number;
  states: number;
  districts: number;
}

export interface ReachSnapshot {
  villages: ReachDataset;
  hostels: ReachDataset;
}

/** The day the figures below were read off the live feed. */
export const PMAJAY_REACH_AS_ON = ${JSON.stringify(asOn)};

export const PMAJAY_REACH_SNAPSHOT: ReachSnapshot = {
${serialiseDataset("villages", reach.villages)}
${serialiseDataset("hostels", reach.hostels)}
};
`;
}

const asOnToday = new Date().toLocaleDateString("en-GB", {
  day: "numeric",
  month: "long",
  year: "numeric",
});

const reach = await fetchReach();

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  const match = current.match(/PMAJAY_REACH_AS_ON = "([^"]+)"/);
  const asOn = match ? match[1] : asOnToday;
  const rendered = render(reach, asOn);
  if (rendered === current) {
    console.log("pmajay map snapshot: in sync with the live feed");
  } else {
    console.log(
      `pmajay map snapshot: DRIFTED from the live feed (mirrored ${asOn}).\n` +
        `  live villages ${reach.villages.total} across ${reach.villages.states} states\n` +
        `  live hostels  ${reach.hostels.total} across ${reach.hostels.states} states\n` +
        `  Run \`node scripts/build-pmajay-map-snapshot.mjs\` to re-mirror, and move AS_ON.`,
    );
  }
  // Report only. A ministry feed moving is news, not a build failure.
  process.exit(0);
}

writeFileSync(OUT, render(reach, asOnToday));
console.log(
  `Wrote ${OUT}\n` +
    `  villages ${reach.villages.total} across ${reach.villages.states} states, ${reach.villages.districts} districts\n` +
    `  hostels  ${reach.hostels.total} across ${reach.hostels.states} states, ${reach.hostels.districts} districts`,
);
