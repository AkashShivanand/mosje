#!/usr/bin/env node
/**
 * Mirror the PM-AJAY map-points feed into a committed snapshot.
 *
 * WHY A SNAPSHOT EXISTS AT ALL. `.claude/rules/live-data-fallback.md`: a figure
 * the department publishes is never replaced on this estate by a dash, a zero or
 * "not yet reported". The reach map therefore needs something to draw when the
 * feed is unreachable, and that something has to be the department's own last
 * published figures rather than an invention.
 *
 * WHY IT IS REDUCED HERE AND NOT IN THE APP. The live payload is ~5.4 MB —
 * 19,768 village points and 203 hostel points. The page needs a binned density
 * field, a row per district and per state, and the hostels in full: about 85 KB.
 * Reducing at the edge keeps the committed mirror readable and keeps the server
 * render from shipping megabytes of coordinates it would immediately discard.
 *
 * WHY IT CALLS THE APP'S OWN REDUCE. `reducePmajayMapPoints` is imported from
 * `apps/hub/src/lib/website/pmajay-map-reduce.ts` and run under Node's type
 * stripping, so the mirror is binned by EXACTLY the code that draws it. A
 * second implementation here would drift, and the failure would be a density
 * field half a cell off its own coastline — visible to nobody until someone
 * looked hard at a coastline.
 *
 * WHY IT IS NOT REGENERATED BY THE BUILD. A snapshot is a point in time; a
 * snapshot that silently follows the feed is not a fallback, it is a second copy
 * of the feed with a stale date on it. Run this deliberately, read the diff, and
 * move `AS_ON` in the same commit:
 *
 *     node scripts/build-pmajay-map-snapshot.mjs
 *     node scripts/build-pmajay-map-snapshot.mjs --from <saved-response.json>
 *     node scripts/build-pmajay-map-snapshot.mjs --check
 *
 * `--from` reads a saved response instead of fetching. That is not a convenience:
 * the production gateway currently answers `504` on this endpoint after ~29s
 * because the payload is too large for it, so a hand-saved response is at times
 * the only way to refresh the mirror at all. The file must be the feed's own
 * body, unedited.
 *
 * `--check` re-reads and reports drift without writing, for the same reason
 * `tools/feed-drift` exists: knowing the mirror has moved is useful; failing a
 * build because a ministry API changed a number is not.
 */

import { writeFileSync, readFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/hub/src/lib/website/pmajay-map-snapshot.ts");
/*
 * The village index is a FETCHED ASSET, not part of the page's bundle.
 *
 * Baked into the snapshot module it took the page's mirrored data from 21 KB
 * gzipped to 106 KB — a fivefold rise, on every visit, for a lookup most
 * readers never run. As a public file it costs the page nothing until someone
 * types in the rail's search. See `VillageName` in the reduce.
 */
const NAMES_OUT = join(ROOT, "apps/hub/public/website/data/pmajay-villages.json");
const REDUCE = join(ROOT, "apps/hub/src/lib/website/pmajay-map-reduce.ts");

const BASE =
  process.env.NEXT_PUBLIC_PMAJAY_MAP_API ??
  process.env.NEXT_PUBLIC_PMAJAY_API ??
  "https://pmajay-api-admin.mosje.in/api/v1/admin/public/reports";

const argv = process.argv.slice(2);
const CHECK = argv.includes("--check");
const fromIdx = argv.indexOf("--from");
const FROM = fromIdx >= 0 ? argv[fromIdx + 1] : null;

/** The feed nests everything under `data`; a saved file may or may not. */
function unwrap(json) {
  const d = json && typeof json === "object" && json.data ? json.data : json;
  if (!d || !Array.isArray(d.vdp_villages) || !Array.isArray(d.hostels)) {
    throw new Error(
      "Response has no `vdp_villages` / `hostels` arrays — is this the map-points body?",
    );
  }
  return d;
}

async function load() {
  if (FROM) {
    const path = resolve(FROM);
    if (!existsSync(path)) throw new Error(`--from file not found: ${path}`);
    console.log(`Reading saved response: ${path}`);
    return unwrap(JSON.parse(readFileSync(path, "utf8")));
  }
  const url = `${BASE}/map-points`;
  console.log(`Fetching ${url} …`);
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 120_000);
  try {
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
    return unwrap(await res.json());
  } finally {
    clearTimeout(timer);
  }
}

/** Today, as the page prints it: "31 August 2026". */
function asOn() {
  return new Date().toLocaleDateString("en-GB", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

function render(snapshot, date) {
  const j = (v) => JSON.stringify(v);
  // One record per line: a 500-row diff is readable, a single 85 KB line is not.
  const rows = (list) => list.map((r) => `  ${j(r)},`).join("\n");

  return `/**
 * PM-AJAY reach, mirrored from the department's \`map-points\` feed.
 *
 * GENERATED — do not hand-edit. Refresh with:
 *
 *     node scripts/build-pmajay-map-snapshot.mjs
 *
 * and move \`PMAJAY_REACH_AS_ON\` in the same commit. It is deliberately NOT
 * rebuilt by \`npm run build\`: a mirror that silently tracks the feed is not a
 * fallback, it is a second copy of the feed wearing a stale date.
 *
 * The shapes live in \`pmajay-map-reduce.ts\`, which is also what produced this
 * file — so the mirror and a live read are the same data reduced by the same
 * code, and cannot disagree about where a village sits.
 */

import type {
  ReachSnapshot,
  HexBin,
  HostelPin,
  DistrictRow,
  StateRow,
  CoverageReport,
} from "./pmajay-map-reduce";

export type { ReachSnapshot, HexBin, HostelPin, DistrictRow, StateRow, CoverageReport };

/** The day the figures below were read off the live feed. */
export const PMAJAY_REACH_AS_ON = ${j(date)};

/** Village density on the hex lattice the map draws. */
const BINS: HexBin[] = [
${rows(snapshot.bins)}
];

/** Every hostel the feed could place, in full. */
const HOSTELS: HostelPin[] = [
${rows(snapshot.hostels)}
];

/** One row per district the scheme has reached, centred on its own points. */
const DISTRICTS: DistrictRow[] = [
${rows(snapshot.districts)}
];

/** One row per state. */
const STATES: StateRow[] = [
${rows(snapshot.states)}
];

/** What the map could and could not draw — rendered, not logged. */
const COVERAGE: CoverageReport = ${JSON.stringify(snapshot.coverage, null, 2)};

export const PMAJAY_REACH_SNAPSHOT: ReachSnapshot = {
  bins: BINS,
  hostels: HOSTELS,
  districts: DISTRICTS,
  states: STATES,
  coverage: COVERAGE,
  districtCount: ${snapshot.districtCount},
  villageTotal: ${snapshot.villageTotal},
  hostelTotal: ${snapshot.hostelTotal},
};
`;
}

/** One village per line, so a name added or corrected shows as one diff row. */
function renderNames(payload, date) {
  const rows = payload.villages.map((v) => `  ${JSON.stringify(v)}`).join(",\n");
  return `{\n  "asOn": ${JSON.stringify(date)},\n  "villages": [\n${rows}\n  ]\n}\n`;
}

function summarise(s) {
  const c = s.coverage;
  return [
    `  villages   ${c.villagesTotal} total · ${c.villagesPlaced} placed · ${c.villagesRepaired} transposed-and-repaired · ${c.villagesUnplaceable} unplaceable · ${c.villagesOffshore} outside India`,
    `  hostels    ${c.hostelsTotal} total · ${c.hostelsPlaced} placed · ${c.hostelsRepaired} transposed-and-repaired · ${c.hostelsUnplaceable} unplaceable · ${c.hostelsOffshore} outside India`,
    `  bins       ${s.bins.length}`,
    `  names      ${c.villagesNamed} of ${c.villagesTotal} villages named` +
      (c.statesWithoutVillageNames.length
        ? ` · none in ${c.statesWithoutVillageNames.join(", ")}`
        : ""),
    `  districts  ${s.districts.length}   states ${s.states.length}`,
  ].join("\n");
}

const { reducePmajayMapPointsFull } = await import(REDUCE);

const raw = await load();
const { snapshot, villageNames } = reducePmajayMapPointsFull(raw);

/*
 * Packed three-to-a-tuple rather than as objects: 10,157 rows of
 * `{"name":…,"state":…,"district":…}` spend 40% of the file on the same three
 * keys repeated. The reader rehydrates them.
 */
const namesPayload = {
  asOn: "",
  villages: villageNames.map((v) => [v.name, v.state, v.district]),
};

console.log(summarise(snapshot));

if (CHECK) {
  if (!existsSync(OUT)) {
    console.error("✗ no snapshot on disk to compare against");
    process.exit(1);
  }
  const current = readFileSync(OUT, "utf8");
  const currentAsOn = /PMAJAY_REACH_AS_ON = "([^"]+)"/.exec(current)?.[1] ?? "";
  // Compare the DATA, not the file: the as-on date differs by construction on
  // every run, and reporting that as drift would make --check useless.
  const next = render(snapshot, currentAsOn);
  const namesCurrent = existsSync(NAMES_OUT) ? readFileSync(NAMES_OUT, "utf8") : "";
  const namesNext = renderNames(namesPayload, currentAsOn);
  if (next === current && namesNext === namesCurrent) {
    console.log("\n✓ mirror matches the feed");
  } else {
    console.log("\n△ the feed has moved since the mirror was taken");
    console.log("  regenerate deliberately:  node scripts/build-pmajay-map-snapshot.mjs");
  }
  process.exit(0);
}

const date = asOn();
writeFileSync(OUT, render(snapshot, date));
mkdirSync(dirname(NAMES_OUT), { recursive: true });
writeFileSync(NAMES_OUT, renderNames(namesPayload, date));
console.log(`\n✓ wrote ${OUT}`);
console.log(`✓ wrote ${NAMES_OUT}`);
console.log(`  PMAJAY_REACH_AS_ON = ${date}`);
