#!/usr/bin/env node
/**
 * GENERATE THE CSS BARREL — because a hand-maintained manifest of 69 files rots.
 *
 * `components.css` is the documented entry point for "Tailwind v3 portals /
 * non-bundled consumers": import it once and get the component styles. On
 * 2026-09-02 it held 26 `@import` lines against 69 stylesheets on disk. The 43
 * that were missing included `modal.css`, `toast.css`, `data-table.css`,
 * `tabs.css`, `breadcrumb.css` and `wizard.css` — so a consumer following the
 * documented path got a design system with most of its CSS silently absent, and
 * nothing said a word, because CSS fails open: an unresolved rule is not an
 * error, it is a component that renders unstyled.
 *
 * Every stylesheet added since the file was last hand-edited was missing. That
 * is the failure mode of any hand-maintained manifest, and the fix is not to
 * edit it more carefully.
 *
 *   npm run build:components-css   regenerate
 *   npm run check:components-css   fail if it is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { readdirSync, statSync } from "node:fs";

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = join(HERE, "..", "packages/design-system");
const OUT = join(PKG, "components.css");

/**
 * Sheets that must NOT be in the barrel.
 *
 * `tokens.css` is the contract this file's header tells you to load first, and
 * importing it here would make the barrel double-declare every custom property.
 * `icons.css` carries an `@font-face` and is loaded once per app by name.
 */
const EXCLUDE = new Set(["tokens.css", "icons.css", "components.css"]);

/** Category order — the order a reader meets these in the documentation nav. */
const ORDER = [
  "foundations",
  "components/actions",
  "components/forms",
  "components/navigation",
  "components/layout",
  "components/data-display",
  "components/dashboard",
  "components/feedback",
  "components/brand",
  "components/auth",
  "components/utilities",
  "demo",
];

function walk(dir, out = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const f = join(dir, e.name);
    if (e.isDirectory()) walk(f, out);
    else if (e.name.endsWith(".css") && !EXCLUDE.has(e.name)) out.push(f);
  }
  return out;
}

const sheets = [
  ...walk(join(PKG, "foundations")),
  ...walk(join(PKG, "components")),
  // `demo` was in ORDER and not in the walk, so the four demo stylesheets were
  // omitted — the same silent-absence failure at smaller scale.
  ...walk(join(PKG, "demo")),
]
  .map((f) => "./" + relative(PKG, f))
  .sort((a, b) => {
    const rank = (p) => {
      const i = ORDER.findIndex((o) => p.startsWith("./" + o));
      return i < 0 ? ORDER.length : i;
    };
    return rank(a) - rank(b) || a.localeCompare(b);
  });

const text = `/* GENERATED by scripts/build-components-css.mjs — do not edit by hand.
   Run \`npm run build:components-css\`; \`npm run check:components-css\` fails when stale.

   All MoSJE design-system component styles. Import once in an app that consumes the
   components (Next apps also get these automatically via each component's own CSS import,
   but this barrel is the entry point for Tailwind v3 portals / non-bundled consumers).
   Requires tokens.css to be loaded first for the --sa-* variables.

   Hand-maintained, this file held 26 imports against 69 stylesheets, so a consumer
   following the documented path silently received a design system missing its modal,
   its toast, its data table and its tabs. It is generated now. */
${sheets.map((s) => `@import "${s}";`).join("\n")}
`;

if (process.argv[2] === "--check") {
  const current = readFileSync(OUT, "utf8");
  if (current !== text) {
    const have = (current.match(/@import/g) ?? []).length;
    console.error(
      `\n✖ components-css: the CSS barrel is stale — ${have} import(s) against ` +
        `${sheets.length} stylesheet(s).\n   Run npm run build:components-css and commit it.\n`,
    );
    process.exit(1);
  }
  console.log(`✔ components-css: ${sheets.length} stylesheet(s), barrel is current.`);
  process.exit(0);
}

writeFileSync(OUT, text);
console.log(`✔ components-css: wrote ${sheets.length} import(s) → packages/design-system/components.css`);
